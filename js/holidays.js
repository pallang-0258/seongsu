// 수동 오버라이드 병합: state.holidayOverrides[dateStr] === true  → 강제 공휴일 지정
//                        state.holidayOverrides[dateStr] === false → 기본 공휴일이어도 강제 해제
function isHoliday(dateStr) {
  const overrides = (typeof state !== 'undefined' && state.holidayOverrides) || {};
  if (Object.prototype.hasOwnProperty.call(overrides, dateStr)) return !!overrides[dateStr];
  return Object.prototype.hasOwnProperty.call(KOREAN_HOLIDAYS_DEFAULT, dateStr);
}
function getHolidayName(dateStr) {
  const overrides = (typeof state !== 'undefined' && state.holidayOverrides) || {};
  if (Object.prototype.hasOwnProperty.call(overrides, dateStr)) {
    if (overrides[dateStr] === false) return null;
    if (overrides[dateStr] === true) return KOREAN_HOLIDAYS_DEFAULT[dateStr] || '지정 휴일';
  }
  return KOREAN_HOLIDAYS_DEFAULT[dateStr] || null;
}
function setHolidayOverride(dateStr, forceValue) {
  if (!state.holidayOverrides) state.holidayOverrides = {};
  state.holidayOverrides[dateStr] = forceValue;
}
function clearHolidayOverride(dateStr) {
  if (state.holidayOverrides) delete state.holidayOverrides[dateStr];
}
// 토글: 현재 isHoliday 상태의 반대로 오버라이드를 설정 (기본값과 같아지면 오버라이드 제거)
function toggleHoliday(dateStr) {
  const cur = isHoliday(dateStr);
  const isDefault = Object.prototype.hasOwnProperty.call(KOREAN_HOLIDAYS_DEFAULT, dateStr);
  const next = !cur;
  if (next === isDefault) clearHolidayOverride(dateStr);
  else setHolidayOverride(dateStr, next);
}
